#!/usr/bin/env node
// Emits crates/acl-types/src/collider_data.rs from src/common/ColliderMap.ts.
//
//     node scripts/port-collider-data.mjs
//
// The collider tables are ~180 lines of SVG path strings and they are the one thing in
// `src/common` that cannot be re-derived — they were traced from the maps by hand
// upstream. Transcribing them by hand a second time is how a wall ends up one decimal
// out and nobody notices until two players hear each other through it, so this reads the
// TypeScript and writes the Rust.
//
// It runs once per change to the tables, not as part of the build: the output is
// committed, and a build that regenerates its own source is a build that can differ from
// what was reviewed.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src/common/ColliderMap.ts'), 'utf8');

/** Pulls one `export const <name> = { ... };` block out by brace balance. */
function block(name) {
    const start = source.indexOf(`export const ${name}`);
    if (start < 0) throw new Error(`${name} not found`);
    // From the `=`, not from the name: the declaration carries a type annotation that is
    // itself a brace block, and starting at the first `{` balances over that instead.
    const assign = source.indexOf('=', start);
    const open = source.indexOf('{', assign);
    let depth = 0;
    for (let i = open; i < source.length; i++) {
    if (source[i] === '{') depth++;
    else if (source[i] === '}') {
        depth--;
        if (depth === 0) return source.slice(open, i + 1);
    }
    }
    throw new Error(`${name} is not brace-balanced`);
}

/** Every `'...'` string literal in a slice, in order. Path data contains no quotes. */
function strings(text) {
    return [...text.matchAll(/'([^']*)'/g)].map((match) => match[1]);
}

/** Splits a block into its `[MapType.NAME]:` entries. */
function byMap(text) {
    const entries = [];
    const marker = /\[MapType\.([A-Z_]+)\]:\s*/g;
    let match = marker.exec(text);
    while (match) {
    const from = marker.lastIndex;
    const next = marker.exec(text);
    entries.push([match[1], text.slice(from, next ? next.index : text.length)]);
    match = next;
    }
    return entries;
}

const colliders = byMap(block('colliderMaps'));
const doors = byMap(block('doorMaps'));

const rustString = (text) => JSON.stringify(text);

/** TypeScript's SCREAMING_CASE members to the Rust enum's names. */
const VARIANTS = {
    THE_SKELD: 'TheSkeld',
    MIRA_HQ: 'MiraHq',
    POLUS: 'Polus',
    THE_SKELD_APRIL: 'TheSkeldApril',
    AIRSHIP: 'Airship',
    FUNGLE: 'Fungle',
    UNKNOWN: 'Unknown',
    SUBMERGED: 'Submerged',
};

function variant(name) {
    const rust = VARIANTS[name];
    // A new map added upstream must fail here rather than silently vanish from the
    // generated table, which would report that no wall is ever in the way on that map.
    if (!rust) throw new Error(`no Rust variant for MapType.${name}`);
    return rust;
}

let out = `// GENERATED by scripts/port-collider-data.mjs from src/common/ColliderMap.ts.
// Do not edit by hand; edit the TypeScript and regenerate, until P8 retires it.
//
// The paths are in their own coordinate space: a world point (x, y) is at
// (x + 40, 40 - y). That offset lives in \`poseCollide\`, not here.

use crate::map::MapType;

/// The wall outlines for one map, as SVG path data.
pub(crate) type ColliderPaths = &'static [&'static str];

/// The wall outlines of every map that has them.
#[must_use]
pub(crate) fn colliders_for(map: MapType) -> Option<ColliderPaths> {
    match map {
`;

for (const [name, body] of colliders) {
    const paths = strings(body);
    if (paths.length === 0) continue;
    out += `\t\tMapType::${variant(name)} => Some(&[\n`;
    for (const path of paths) out += `\t\t\t${rustString(path)},\n`;
    out += `\t\t]),\n`;
}
out += `\t\t_ => None,
    }
}

/// One door's outline, by the door id the game reports.
#[must_use]
pub(crate) fn door_for(map: MapType, door_id: u32) -> Option<&'static str> {
    match map {
`;

for (const [name, body] of doors) {
    // Door entries are `<id>: '<path>',`, and an id may be absent for a door with no wall.
    const pairs = [...body.matchAll(/(\d+)\s*:\s*'([^']*)'/g)];
    if (pairs.length === 0) continue;
    out += `\t\tMapType::${variant(name)} => match door_id {\n`;
    for (const [, id, path] of pairs) out += `\t\t\t${id} => Some(${rustString(path)}),\n`;
    out += `\t\t\t_ => None,\n\t\t},\n`;
}
out += `\t\t_ => None,
    }
}
`;

const target = join(root, 'crates/acl-types/src/collider_data.rs');
writeFileSync(target, out, 'utf8');

// Indentation is rustfmt's business, not this script's. Emitting it by hand means the
// generated file fails `cargo fmt --check` the moment the nesting changes, and CI then
// blocks on a file nobody edited.
execFileSync('cargo', ['fmt', '-p', 'acl-types'], { cwd: root, stdio: 'inherit' });

const colliderCount = colliders.reduce((sum, [, body]) => sum + strings(body).length, 0);
const doorCount = doors.reduce((sum, [, body]) => sum + [...body.matchAll(/\d+\s*:\s*'/g)].length, 0);
console.log(`wrote ${colliderCount} collider paths and ${doorCount} doors to ${target}`);
